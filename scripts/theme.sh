#!/bin/bash
# Switch the colour scheme for the whole desktop (Hyprland, hyprlock,
# hyprlauncher, waybar, wofi, foot, kitty, tmux, btop, nvim).
#
# Palettes live in scripts/themes/<name>.sh. Applying one renders per-app
# colour files into ~/.local/state/theme/, which the app configs include,
# then reloads whatever is currently running.

set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "$(readlink -f -- "${BASH_SOURCE[0]}")")" && pwd)"
readonly THEMES_DIR="$SCRIPT_DIR/themes"
readonly OUT_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/theme"
readonly DEFAULT_THEME=gruvbox
readonly BTOP_CONF="${XDG_CONFIG_HOME:-$HOME/.config}/btop/btop.conf"

usage() {
    cat <<EOF
Usage: ${0##*/} [THEME | --list | --current | --init | --pick]

  THEME       Apply a theme and reload running apps
  --list      List available themes
  --current   Print the active theme
  --init      Generate colour files if none exist yet (no reloads)
  --pick      Choose a theme with wofi (default with no arguments)
EOF
}

die() {
    printf 'ERROR: %s\n' "$*" >&2
    exit 1
}

list_themes() {
    local f
    for f in "$THEMES_DIR"/*.sh; do
        f="${f##*/}"
        printf '%s\n' "${f%.sh}"
    done
}

current_theme() {
    if [[ -r "$OUT_DIR/current" ]]; then
        cat "$OUT_DIR/current"
    else
        printf '%s\n' "$DEFAULT_THEME"
    fi
}

# write_out FILE  (content on stdin) — atomic, so apps never read half a file
write_out() {
    cat >"$OUT_DIR/$1.tmp"
    mv -f -- "$OUT_DIR/$1.tmp" "$OUT_DIR/$1"
}

load_palette() {
    local file="$THEMES_DIR/$1.sh"
    [[ -f "$file" ]] || die "Unknown theme '$1' (available: $(list_themes | tr '\n' ' '))"
    # shellcheck source=/dev/null
    . "$file"

    local var
    for var in NAME BG BG_ALT SURFACE FG FG_BRIGHT MUTED BORDER_ACTIVE \
        BORDER_INACTIVE SHADOW SEL_FG SEL_BG RED GREEN YELLOW BLUE MAGENTA \
        CYAN WHITE BBLACK BRED BGREEN BYELLOW BBLUE BMAGENTA BCYAN BWHITE \
        ORANGE GREEN_DIM BLUE_DIM NVIM_COLORSCHEME BTOP_THEME; do
        [[ -n "${!var:-}" ]] || die "Theme '$1' does not define $var"
    done
}

generate() {
    mkdir -p "$OUT_DIR"

    write_out hypr.lua <<EOF
-- generated by theme.sh ($NAME)
hl.config({
    general = {
        col = {
            active_border   = "rgba(${BORDER_ACTIVE}ff)",
            inactive_border = "rgba(${BORDER_INACTIVE}ff)",
        },
    },
    decoration = {
        shadow = { color = "rgba(${SHADOW}ee)" },
    },
})
EOF

    write_out hyprtoolkit.conf <<EOF
# generated by theme.sh ($NAME)
background       = 0xff$BG
base             = 0xff$BG_ALT
alternate_base   = 0xff$SURFACE
text             = 0xff$FG
bright_text      = 0xff$FG_BRIGHT
link_text        = 0xff$BBLUE
accent           = 0xff$BORDER_ACTIVE
accent_secondary = 0xff$YELLOW
EOF

    write_out hyprlock.conf <<EOF
# generated by theme.sh ($NAME)
\$lock_text  = rgba(${FG_BRIGHT}ff)
\$lock_panel = rgba(${BG_ALT}ff)
\$lock_inner = rgba(${BG_ALT}cc)
\$lock_outer = rgba(${BLUE}ff)
\$lock_check = rgba(${BGREEN}ff)
\$lock_fail  = rgba(${BRED}ff)
EOF

    write_out foot.ini <<EOF
# generated by theme.sh ($NAME)
[colors-dark]
alpha=0.75
blur=yes

foreground=$FG
background=$BG

selection-foreground=$SEL_FG
selection-background=$SEL_BG

cursor=$MUTED $FG

regular0=$BG
regular1=$RED
regular2=$GREEN
regular3=$YELLOW
regular4=$BLUE
regular5=$MAGENTA
regular6=$CYAN
regular7=$WHITE

bright0=$BBLACK
bright1=$BRED
bright2=$BGREEN
bright3=$BYELLOW
bright4=$BBLUE
bright5=$BMAGENTA
bright6=$BCYAN
bright7=$BWHITE
EOF

    write_out kitty.conf <<EOF
# generated by theme.sh ($NAME)
foreground #$FG
background #$BG
selection_foreground #$SEL_FG
selection_background #$SEL_BG
cursor #$FG
url_color #$BBLUE

color0 #$BG
color1 #$RED
color2 #$GREEN
color3 #$YELLOW
color4 #$BLUE
color5 #$MAGENTA
color6 #$CYAN
color7 #$WHITE
color8 #$BBLACK
color9 #$BRED
color10 #$BGREEN
color11 #$BYELLOW
color12 #$BBLUE
color13 #$BMAGENTA
color14 #$BCYAN
color15 #$BWHITE
EOF

    write_out tmux.conf <<EOF
# generated by theme.sh ($NAME)
set -g status-style "bg=default,fg=#$GREEN"
set -g message-style "bg=#$SURFACE,fg=#$FG"
set -g pane-border-style "fg=#$SURFACE"
set -g pane-active-border-style "fg=#$BORDER_ACTIVE"
set -g window-status-style "fg=#$MUTED"
set -g window-status-current-style "fg=#$BYELLOW,bold"
set -g mode-style "bg=#$SEL_BG,fg=#$SEL_FG"
set -g display-panes-active-colour "#$BYELLOW"
set -g display-panes-colour "#$MUTED"
EOF

    # waybar and wofi are both GTK CSS
    write_out colors.css <<EOF
/* generated by theme.sh ($NAME) */
@define-color bg #$BG;
@define-color bg_alt #$BG_ALT;
@define-color surface #$SURFACE;
@define-color fg #$FG;
@define-color fg_bright #$FG_BRIGHT;
@define-color muted #$MUTED;
@define-color red #$RED;
@define-color bred #$BRED;
@define-color green #$GREEN;
@define-color bgreen #$BGREEN;
@define-color green_dim #$GREEN_DIM;
@define-color yellow #$YELLOW;
@define-color byellow #$BYELLOW;
@define-color blue #$BLUE;
@define-color bblue #$BBLUE;
@define-color blue_dim #$BLUE_DIM;
@define-color cyan #$CYAN;
@define-color bcyan #$BCYAN;
@define-color orange #$ORANGE;
EOF

    # GTK3 apps (thunar, ...): user overrides layered on the installed GTK theme
    write_out gtk3.css <<EOF
/* generated by theme.sh ($NAME) */
@define-color theme_bg_color #$BG;
@define-color theme_base_color #$BG;
@define-color theme_fg_color #$FG;
@define-color theme_text_color #$FG;
@define-color theme_selected_bg_color #$BLUE;
@define-color theme_selected_fg_color #$FG_BRIGHT;
@define-color theme_unfocused_bg_color #$BG;
@define-color theme_unfocused_base_color #$BG;
@define-color theme_unfocused_fg_color #$MUTED;
@define-color theme_unfocused_text_color #$MUTED;
@define-color theme_unfocused_selected_bg_color #$SURFACE;
@define-color theme_unfocused_selected_fg_color #$FG;
@define-color insensitive_bg_color #$BG;
@define-color insensitive_fg_color #$MUTED;
@define-color borders #$SURFACE;
@define-color unfocused_borders #$SURFACE;
@define-color bg_color #$BG;
@define-color fg_color #$FG;
@define-color base_color #$BG;
@define-color text_color #$FG;
@define-color selected_bg_color #$BLUE;
@define-color selected_fg_color #$FG_BRIGHT;

window, .background, dialog, messagedialog { background-color: #$BG; color: #$FG; }
.view, iconview, textview text, treeview.view, list, row { background-color: #$BG; color: #$FG; }
.view:selected, iconview:selected, row:selected, treeview.view:selected,
.view:selected:focus, row:selected:focus, selection { background-color: #$BLUE; color: #$FG_BRIGHT; }
headerbar, .titlebar, toolbar, .toolbar, statusbar, actionbar, .path-bar, .inline-toolbar {
    background-image: none; background-color: #$BG_ALT; color: #$FG; border-color: #$SURFACE; box-shadow: none;
}
.sidebar, placessidebar, placessidebar list, placessidebar row { background-color: #$BG_ALT; color: #$FG; }
placessidebar row:selected { background-color: #$SURFACE; color: #$FG_BRIGHT; }
menu, .menu, .popup, popover, popover.background, menuitem { background-color: #$BG_ALT; color: #$FG; border-color: #$SURFACE; }
menuitem:hover, modelbutton:hover { background-color: #$SURFACE; color: #$FG_BRIGHT; }
entry, spinbutton, combobox { background-image: none; background-color: #$BG_ALT; color: #$FG; border-color: #$SURFACE; }
button { background-image: none; background-color: #$SURFACE; color: #$FG; border-color: #$SURFACE; box-shadow: none; text-shadow: none; }
button:hover { background-color: #$MUTED; color: #$BG; }
button:checked, button:active { background-color: #$BLUE; color: #$FG_BRIGHT; }
scrollbar slider { background-color: #$MUTED; }
scrollbar, scrollbar trough { background-color: #$BG; }
separator { background-color: #$SURFACE; }
tooltip, tooltip.background { background-color: #$SURFACE; color: #$FG; border: 1px solid #$MUTED; }
EOF

    # terminal escape sequences, replayed into open terminals on switch
    {
        # foot treats a plain OSC 11 as opaque; rgba:rr/gg/bb/aa keeps the 75% alpha
        printf '\033]10;#%s\033\\\033]11;rgba:%s/%s/%s/bf\033\\\033]12;#%s\033\\' \
            "$FG" "${BG:0:2}" "${BG:2:2}" "${BG:4:2}" "$FG"
        local i colors=("$BG" "$RED" "$GREEN" "$YELLOW" "$BLUE" "$MAGENTA" "$CYAN" "$WHITE"
            "$BBLACK" "$BRED" "$BGREEN" "$BYELLOW" "$BBLUE" "$BMAGENTA" "$BCYAN" "$BWHITE")
        for i in "${!colors[@]}"; do
            printf '\033]4;%d;#%s\033\\' "$i" "${colors[$i]}"
        done
    } | write_out osc

    # GTK3 reads ~/.config/gtk-3.0/gtk.css; link it unless the user has their own
    local gtk_css="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-3.0/gtk.css"
    mkdir -p "${gtk_css%/*}"
    if [[ ! -e "$gtk_css" || -L "$gtk_css" ]]; then
        ln -sfn "$OUT_DIR/gtk3.css" "$gtk_css"
    fi

    printf '%s\n' "$NVIM_COLORSCHEME" | write_out nvim
    printf '%s\n' "$THEME" | write_out current
}

set_btop_theme() {
    [[ -f "$BTOP_CONF" ]] || return 0
    sed -i -E "s|^color_theme = .*|color_theme = \"$BTOP_THEME\"|" "$BTOP_CONF"
}

reload_apps() {
    local pty sock

    if command -v hyprctl >/dev/null 2>&1; then
        hyprctl reload >/dev/null 2>&1 || true
    fi

    pkill -USR2 -x waybar 2>/dev/null || true
    pkill -USR2 -x btop 2>/dev/null || true
    pkill -USR1 -x kitty 2>/dev/null || true

    # GTK apps re-read gtk.css when the GTK theme setting changes
    if command -v gsettings >/dev/null 2>&1; then
        local gtk_theme
        gtk_theme="$(gsettings get org.gnome.desktop.interface gtk-theme 2>/dev/null || true)"
        gtk_theme="${gtk_theme//\'/}"
        if [[ -n "$gtk_theme" ]]; then
            gsettings set org.gnome.desktop.interface gtk-theme Adwaita >/dev/null 2>&1 || true
            gsettings set org.gnome.desktop.interface gtk-theme "$gtk_theme" >/dev/null 2>&1 || true
        fi
    fi

    if command -v tmux >/dev/null 2>&1 && tmux has-session 2>/dev/null; then
        tmux source-file "$OUT_DIR/tmux.conf" 2>/dev/null || true
        tmux refresh-client -S 2>/dev/null || true
    fi

    # running terminals (foot, kitty, ...): recolour via OSC escapes
    # Skip tmux pane ptys: tmux would remember the colours and paint them as
    # opaque cells. Reset any it already holds, and let the outer terminal
    # (the tmux client's pty) do the recolouring instead.
    local -A pane_ptys=()
    if command -v tmux >/dev/null 2>&1; then
        while read -r pty; do
            [[ -n "$pty" ]] && pane_ptys[$pty]=1
        done < <(tmux list-panes -a -F '#{pane_tty}' 2>/dev/null || true)
    fi
    for pty in /dev/pts/[0-9]*; do
        [[ -w "$pty" ]] || continue
        if [[ -n "${pane_ptys[$pty]:-}" ]]; then
            printf '\033]110\033\\\033]111\033\\\033]112\033\\' >"$pty" 2>/dev/null || true
        else
            cat "$OUT_DIR/osc" >"$pty" 2>/dev/null || true
        fi
    done

    # running neovim instances
    if command -v nvim >/dev/null 2>&1; then
        for sock in "${XDG_RUNTIME_DIR:-/run/user/$UID}"/nvim.*.0; do
            [[ -S "$sock" ]] || continue
            timeout 2 nvim --server "$sock" --remote-expr \
                'luaeval("require(\"taylor.theme\").apply()")' >/dev/null 2>&1 || true
        done
    fi
}

pick_theme() {
    command -v wofi >/dev/null 2>&1 || die "wofi is required for the picker"
    local choice
    choice="$(list_themes | wofi --dmenu --prompt "Theme ($(current_theme))")" || exit 0
    [[ -n "$choice" ]] && apply_theme "$choice"
}

apply_theme() {
    THEME="$1"
    load_palette "$THEME"
    generate
    set_btop_theme
    reload_apps
    printf 'Applied %s\n' "$NAME"
}

main() {
    case "${1:---pick}" in
        -h | --help) usage ;;
        --list) list_themes ;;
        --current) current_theme ;;
        --pick) pick_theme ;;
        --init)
            if [[ ! -f "$OUT_DIR/current" ]]; then
                THEME="$DEFAULT_THEME"
                load_palette "$THEME"
                generate
                set_btop_theme
            fi
            ;;
        -*) usage >&2; exit 1 ;;
        *) apply_theme "$1" ;;
    esac
}

main "$@"
